/**
 * @file wms-phone.js — เบอร์โทรจากชีต ให้กลับมาอยู่ในรูปที่โทรออกได้
 *
 * ชีตเก็บเบอร์เป็นตัวเลข ไม่ใช่ข้อความ ศูนย์นำหน้าจึงหายไปตั้งแต่ในชีตแล้ว
 * ในไฟล์ตัวอย่างจริง 201 จาก 214 ช่องเป็นแบบนี้ — "0838187834" กลายเป็น
 * "838187834" ซึ่งกดโทรออกไม่ติด และคนอ่านใบงานก็ไม่รู้ว่าต้องเติม 0 เอง
 *
 * เติมศูนย์คืนเฉพาะกรณีที่รู้แน่ ๆ ว่าหายไป ไม่เดาให้กับเลขที่ไม่เข้าเค้า —
 * เลขที่ไม่รู้ว่าคืออะไรส่งคืนตามเดิม ดีกว่าแต่งให้ดูเหมือนเบอร์แล้วผิด
 *
 * โหลดเป็น classic script เปิดเป็น window.WmsPhone
 */
(function () {
  'use strict';

  /**
   * @param {*} v ค่าจากชีต (ตัวเลขหรือข้อความ)
   * @returns {string} เบอร์ที่จัดรูปแล้ว หรือค่าเดิมถ้าไม่เข้าเค้าเบอร์ไทย
   */
  function format(v) {
    var raw = String(v == null ? '' : v).trim();
    if (!raw) return '';

    var d = raw.replace(/\D/g, '');
    if (!d) return '';                       // "-" หรือข้อความล้วน = ไม่มีเบอร์

    // เขียนมาเป็นรหัสประเทศ (+66 / 66) — ตัดออกแล้วใส่ 0 แทน
    if (d.length === 11 && d.slice(0, 2) === '66') d = '0' + d.slice(2);

    // ศูนย์นำหน้าหายเพราะถูกเก็บเป็นตัวเลข: มือถือเหลือ 9 หลัก เบอร์บ้านเหลือ 8
    if (d.length === 9 && d[0] !== '0') d = '0' + d;
    else if (d.length === 8 && d[0] !== '0') d = '0' + d;

    if (d.length === 10 && d[0] === '0') return d.slice(0, 3) + '-' + d.slice(3);
    if (d.length === 9 && d[0] === '0') return d.slice(0, 2) + '-' + d.slice(2);

    /* ยาวผิดจากที่รู้จัก — อาจเป็นเบอร์ต่อ เบอร์ต่างประเทศ หรือคนกรอกสองเบอร์
       ติดกัน ส่งคืนตามที่เขียนมา ให้คนอ่านตัดสินเอง ดีกว่าจัดรูปให้ผิด */
    return raw;
  }

  window.WmsPhone = { format: format };
})();
