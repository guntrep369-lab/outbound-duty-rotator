/**
 * public/wms-phone.js — คืนศูนย์นำหน้าที่ชีตทำหายให้เบอร์โทร
 *
 * รูปแบบทั้งหมดมาจากไฟล์ตัวอย่างจริง 214 ช่องเบอร์:
 *   ตัวเลข 9 หลัก 201 ช่อง · ข้อความมีขีด 12 ช่อง · ตัวเลข 11 หลักขึ้นต้น 66 หนึ่งช่อง
 */
import { describe, it, expect, beforeEach } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

const SRC = fs.readFileSync(path.resolve(__dirname, '../../public/wms-phone.js'), 'utf8');

let WmsPhone;
beforeEach(() => {
  const win = {};
  new Function('window', SRC)(win);
  WmsPhone = win.WmsPhone;
});

const f = (v) => WmsPhone.format(v);

describe('เบอร์ที่ศูนย์นำหน้าหายไปเพราะชีตเก็บเป็นตัวเลข', () => {
  it('มือถือ 9 หลัก เติม 0 คืนแล้วใส่ขีด', () => {
    expect(f(838187834)).toBe('083-8187834');
    expect(f(948956168)).toBe('094-8956168');
    expect(f(909495199)).toBe('090-9495199');
  });

  it('รับได้ทั้งตัวเลขและข้อความ — GAS ส่งมาได้ทั้งสองแบบ', () => {
    expect(f('838187834')).toBe('083-8187834');
    expect(f(838187834)).toBe('083-8187834');
  });

  it('เบอร์บ้าน 8 หลัก เติม 0 แล้วตัดเป็น 2-7', () => {
    expect(f(21234567)).toBe('02-1234567');
    expect(f('021234567')).toBe('02-1234567');
  });

  it('รหัสประเทศ 66 แปลงกลับเป็น 0', () => {
    expect(f(66894448803)).toBe('089-4448803');
    expect(f('+66894448803')).toBe('089-4448803');
  });
});

describe('ของที่ถูกอยู่แล้ว ต้องไม่ถูกทำให้เพี้ยน', () => {
  it('เบอร์ที่จัดรูปมาแล้ว ส่งกลับเหมือนเดิม', () => {
    expect(f('083-8187834')).toBe('083-8187834');
  });

  it('จัดรูปซ้ำได้ผลเดิม — ข้อมูลผ่านหลายชั้นได้โดยไม่เพี้ยน', () => {
    expect(f(f(f(838187834)))).toBe('083-8187834');
  });

  it('เบอร์ 10 หลักที่มี 0 อยู่แล้ว ไม่เติมซ้ำ', () => {
    expect(f('0838187834')).toBe('083-8187834');
  });

  it('เขียนมาแบบมีวรรคหรือวงเล็บ ก็อ่านออก', () => {
    expect(f('083 818 7834')).toBe('083-8187834');
    expect(f('(083) 818-7834')).toBe('083-8187834');
  });
});

describe('ไม่เดาให้กับสิ่งที่ไม่รู้ว่าคืออะไร', () => {
  it('ว่างหรือมีแต่ขีด = ไม่มีเบอร์', () => {
    for (const v of ['', '   ', '-', '--', null, undefined]) expect(f(v)).toBe('');
  });

  it('ยาวผิดจากที่รู้จัก ส่งคืนตามที่เขียนมา ไม่แต่งให้ดูเหมือนเบอร์', () => {
    expect(f('12345')).toBe('12345');
    expect(f('081-1111111 / 082-2222222')).toBe('081-1111111 / 082-2222222');
  });

  it('10 หลักที่ไม่ได้ขึ้นต้นด้วย 0 ไม่ใช่เบอร์ไทย อย่าไปตัดขีดให้', () => {
    expect(f('1234567890')).toBe('1234567890');
  });
});
